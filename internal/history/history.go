// Package history reads Claude Code's own session files (JSON Lines under
// <config dir>/projects/<folder>/<session>.jsonl) and yields the text a person typed and the text
// Claude answered. It is a deterministic parser: no model, no network, and nothing is written.
//
// The file layout is not a published interface. The shape this parser understands was observed
// on 2026-11-20 (key names only, never content) and is recorded as ParserVersion; anything it
// does not recognise is counted and skipped, never guessed at.
package history

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"io"
	"strings"
	"time"
)

// ParserVersion identifies the rules below. Stored with every imported event.
const ParserVersion = 1

// MaxLineBytes bounds one line. Session files contain very large bookkeeping lines; a line over
// this size is skipped and counted.
const MaxLineBytes = 64 << 20

// Turn is one piece of text from a session file.
type Turn struct {
	SessionID string
	UUID      string // unique per line in the file; the idempotency key is built from it
	Cwd       string
	Who       string // "user" or "assistant"
	Text      string
	At        time.Time
}

// Stats counts what a file contained.
type Stats struct {
	Lines        int `json:"lines"`
	Turns        int `json:"turns"`
	BadLines     int `json:"unreadable_lines"`
	Oversize     int `json:"oversize_lines"`
	Sidechain    int `json:"subagent_lines_skipped"`
	Injected     int `json:"injected_text_skipped"`
	NoText       int `json:"lines_without_text"`
	MissingField int `json:"lines_missing_fields"`
}

// Add accumulates another file's counts.
func (s *Stats) Add(o Stats) {
	s.Lines += o.Lines
	s.Turns += o.Turns
	s.BadLines += o.BadLines
	s.Oversize += o.Oversize
	s.Sidechain += o.Sidechain
	s.Injected += o.Injected
	s.NoText += o.NoText
	s.MissingField += o.MissingField
}

type line struct {
	Type             string `json:"type"`
	IsSidechain      bool   `json:"isSidechain"`
	IsMeta           bool   `json:"isMeta"`
	IsCompactSummary bool   `json:"isCompactSummary"`
	Cwd              string `json:"cwd"`
	SessionID        string `json:"sessionId"`
	UUID             string `json:"uuid"`
	Timestamp        string `json:"timestamp"`
	Message          *struct {
		Role    string          `json:"role"`
		Content json.RawMessage `json:"content"`
	} `json:"message"`
}

// injectedPrefixes mark user-role text that Claude Code wrote itself (command wrappers, hook
// output, reminders, background-task notices). A person did not type these.
var injectedPrefixes = []string{
	"<command-name>", "<command-message>", "<command-args>", "<local-command-stdout>", "<local-command-stderr>",
	"<local-command-caveat>", "<system-reminder>", "<task-notification>", "<user-prompt-submit-hook>", "<bash-input>",
	"<bash-stdout>", "<bash-stderr>", "Caveat: The messages below were generated by the user while running local commands",
	"[Request interrupted by user",
}

func injected(text string) bool {
	t := strings.TrimLeft(text, " \t\r\n")
	for _, p := range injectedPrefixes {
		if strings.HasPrefix(t, p) {
			return true
		}
	}
	return false
}

// text extracts the plain text of a message's content: a string, or the "text" blocks of a list.
// Thinking, tool calls, tool results and images are not text a person or Claude said.
func text(raw json.RawMessage) string {
	raw = bytes.TrimSpace(raw)
	if len(raw) == 0 {
		return ""
	}
	if raw[0] == '"' {
		var s string
		if json.Unmarshal(raw, &s) != nil {
			return ""
		}
		return s
	}
	var blocks []struct {
		Type string `json:"type"`
		Text string `json:"text"`
	}
	if json.Unmarshal(raw, &blocks) != nil {
		return ""
	}
	var parts []string
	for _, b := range blocks {
		if b.Type == "text" && strings.TrimSpace(b.Text) != "" && !injected(b.Text) {
			parts = append(parts, b.Text)
		}
	}
	return strings.Join(parts, "\n\n")
}

// Parse reads one session file and calls fn for every turn, in file order. It returns an error
// only when reading fails; malformed content is counted in Stats.
func Parse(r io.Reader, fn func(Turn)) (Stats, error) {
	var st Stats
	br := bufio.NewReaderSize(r, 1<<20)
	for {
		raw, tooLong, err := readLine(br)
		if len(raw) > 0 || tooLong {
			st.Lines++
			switch {
			case tooLong:
				st.Oversize++
			default:
				one(raw, &st, fn)
			}
		}
		if errors.Is(err, io.EOF) {
			return st, nil
		}
		if err != nil {
			return st, err
		}
	}
}

func one(raw []byte, st *Stats, fn func(Turn)) {
	// Cheap rejection before decoding: most lines are bookkeeping.
	if !bytes.Contains(raw, []byte(`"message"`)) {
		return
	}
	var l line
	if json.Unmarshal(raw, &l) != nil {
		st.BadLines++
		return
	}
	if (l.Type != "user" && l.Type != "assistant") || l.Message == nil {
		return
	}
	if l.IsSidechain {
		st.Sidechain++
		return
	}
	if l.Message.Role != l.Type {
		st.MissingField++
		return
	}
	body := text(l.Message.Content)
	if l.Type == "user" && (l.IsMeta || l.IsCompactSummary || injected(body)) {
		st.Injected++
		return
	}
	if strings.TrimSpace(body) == "" {
		st.NoText++
		return
	}
	at, err := time.Parse(time.RFC3339Nano, l.Timestamp)
	if err != nil || l.SessionID == "" || l.UUID == "" || l.Cwd == "" {
		st.MissingField++
		return
	}
	st.Turns++
	fn(Turn{SessionID: l.SessionID, UUID: l.UUID, Cwd: l.Cwd, Who: l.Type, Text: body, At: at.UTC()})
}

// readLine returns the next line without its newline. A line longer than MaxLineBytes is
// consumed and reported as tooLong with no content.
func readLine(br *bufio.Reader) (raw []byte, tooLong bool, err error) {
	for {
		part, e := br.ReadSlice('\n')
		if !tooLong {
			if len(raw)+len(part) > MaxLineBytes {
				tooLong, raw = true, nil
			} else {
				raw = append(raw, part...)
			}
		}
		if errors.Is(e, bufio.ErrBufferFull) {
			continue
		}
		return bytes.TrimRight(raw, "\r\n"), tooLong, e
	}
}
