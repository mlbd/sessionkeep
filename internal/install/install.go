// Package install puts SessionKeep in a stable per-user location and takes it out again.
//
// It only ever creates, and only ever removes, the files it lists in its own install record.
// It never edits a Claude Code setting: it generates a plugin and a one-plugin local marketplace
// next to the binary, and tells the user the two commands that enable it.
package install

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"time"

	"sessionkeep/internal/plugin"
)

// EnvInstallDir overrides where SessionKeep installs itself; for test sandboxes.
const EnvInstallDir = "SESSIONKEEP_INSTALL_DIR"

// MarketplaceName is the name of the generated local marketplace.
const MarketplaceName = "sessionkeep-local"

const recordName = "install.json"

// Dir returns the per-user install directory.
func Dir(goos string, getenv func(string) string) (string, error) {
	if d := getenv(EnvInstallDir); d != "" {
		if !filepath.IsAbs(d) {
			return "", fmt.Errorf("%s must be an absolute path", EnvInstallDir)
		}
		return filepath.Clean(d), nil
	}
	switch goos {
	case "windows":
		if base := getenv("LOCALAPPDATA"); filepath.IsAbs(base) {
			return filepath.Join(base, "Programs", "SessionKeep"), nil
		}
		return "", errors.New("LOCALAPPDATA is not set to an absolute path")
	case "darwin":
		if home := getenv("HOME"); filepath.IsAbs(home) {
			return filepath.Join(home, "Library", "Application Support", "SessionKeep", "app"), nil
		}
	default:
		if home := getenv("HOME"); filepath.IsAbs(home) {
			return filepath.Join(home, ".local", "lib", "sessionkeep"), nil
		}
	}
	return "", errors.New("HOME is not set to an absolute path")
}

// Record is what an install wrote, so uninstall removes exactly that and nothing else.
type Record struct {
	Version     string   `json:"version"`
	InstalledAt string   `json:"installed_at"`
	Binary      string   `json:"binary"`
	Marketplace string   `json:"marketplace_dir"`
	PluginDir   string   `json:"plugin_dir"`
	WithMCP     bool     `json:"with_mcp"`
	Files       []string `json:"files"` // relative to the install directory
}

// BinaryName is the installed program's file name on this system.
func BinaryName() string {
	if runtime.GOOS == "windows" {
		return "sessionkeep.exe"
	}
	return "sessionkeep"
}

// Load returns the install record in dir, or nil if SessionKeep is not installed there.
func Load(dir string) (*Record, error) {
	raw, err := os.ReadFile(filepath.Join(dir, recordName))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var r Record
	if err := json.Unmarshal(raw, &r); err != nil {
		return nil, fmt.Errorf("install record is damaged: %w", err)
	}
	return &r, nil
}

// Install copies the program at self into dir, generates the plugin and marketplace, and writes
// the record. Running it again updates in place.
func Install(dir, self, version string, withMCP bool, now time.Time) (*Record, error) {
	if entries, err := os.ReadDir(dir); err == nil && len(entries) > 0 {
		if rec, err := Load(dir); err != nil || rec == nil {
			return nil, fmt.Errorf("%s exists, is not empty and was not created by SessionKeep; nothing was changed", dir)
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	bin := filepath.Join(dir, BinaryName())
	if !sameFile(self, bin) {
		if err := replaceBinary(self, bin); err != nil {
			return nil, fmt.Errorf("copy the program: %w", err)
		}
	}
	market := filepath.Join(dir, "claude-plugin")
	plug := filepath.Join(market, plugin.Name)
	if err := plugin.Write(plug, bin, version, withMCP); err != nil {
		return nil, err
	}
	manifest := map[string]any{
		"name":        MarketplaceName,
		"description": "SessionKeep as installed on this computer. Generated by `sessionkeep install`; it lists the one local plugin.",
		"owner":       map[string]string{"name": "SessionKeep (this computer)"},
		"plugins": []map[string]any{{
			"name": plugin.Name, "source": "./" + plugin.Name, "version": version,
			"description": "Local-first developer memory for projects you registered.",
		}},
	}
	raw, _ := json.MarshalIndent(manifest, "", "  ")
	if err := os.MkdirAll(filepath.Join(market, ".claude-plugin"), 0o755); err != nil {
		return nil, err
	}
	if err := os.WriteFile(filepath.Join(market, ".claude-plugin", "marketplace.json"), append(raw, '\n'), 0o644); err != nil {
		return nil, err
	}

	rec := &Record{Version: version, InstalledAt: now.UTC().Format(time.RFC3339), Binary: bin, Marketplace: market, PluginDir: plug, WithMCP: withMCP}
	filepath.Walk(dir, func(p string, fi os.FileInfo, err error) error {
		if err == nil && !fi.IsDir() && filepath.Base(p) != recordName && !strings.Contains(filepath.Base(p), ".old-") {
			rel, _ := filepath.Rel(dir, p)
			rec.Files = append(rec.Files, filepath.ToSlash(rel))
		}
		return nil
	})
	raw, _ = json.MarshalIndent(rec, "", "  ")
	if err := os.WriteFile(filepath.Join(dir, recordName), append(raw, '\n'), 0o644); err != nil {
		return nil, err
	}
	return rec, nil
}

func sameFile(a, b string) bool {
	fa, errA := os.Stat(a)
	fb, errB := os.Stat(b)
	return errA == nil && errB == nil && os.SameFile(fa, fb)
}

// replaceBinary puts a copy of src at dst. A program that is running cannot be overwritten on
// Windows but can be renamed, so an existing dst is moved aside first; leftovers from earlier
// updates are removed when they are no longer in use.
func replaceBinary(src, dst string) error {
	old, _ := filepath.Glob(dst + ".old-*")
	for _, o := range old {
		os.Remove(o)
	}
	tmp := dst + ".new"
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o755)
	if err != nil {
		return err
	}
	if _, err = io.Copy(out, in); err == nil {
		err = out.Sync()
	}
	if cerr := out.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		os.Remove(tmp)
		return err
	}
	if _, err := os.Stat(dst); err == nil {
		aside := fmt.Sprintf("%s.old-%d", dst, time.Now().UnixNano())
		if err := os.Rename(dst, aside); err != nil {
			os.Remove(tmp)
			return err
		}
		os.Remove(aside) // succeeds unless the old program is still running; then it is cleaned up next time
	}
	return os.Rename(tmp, dst)
}

// Uninstall removes what the record lists, then the directories it emptied. If self is the
// installed program (it is running and cannot delete itself on Windows), that one file is moved
// to the system temp directory instead and its new location is returned in moved.
func Uninstall(dir, self string) (removed []string, moved string, err error) {
	rec, err := Load(dir)
	if err != nil {
		return nil, "", err
	}
	if rec == nil {
		return nil, "", ErrNotInstalled
	}
	for _, rel := range rec.Files {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if !strings.HasPrefix(filepath.Clean(p), filepath.Clean(dir)+string(os.PathSeparator)) {
			continue // a record must never lead outside the install directory
		}
		if sameFile(p, self) && runtime.GOOS == "windows" {
			target := filepath.Join(os.TempDir(), fmt.Sprintf("sessionkeep-removed-%d.exe", time.Now().UnixNano()))
			if os.Rename(p, target) == nil {
				moved = target
				removed = append(removed, rel)
				continue
			}
		}
		if err := os.Remove(p); err == nil || errors.Is(err, os.ErrNotExist) {
			removed = append(removed, rel)
		} else {
			return removed, moved, fmt.Errorf("remove %s: %w", p, err)
		}
	}
	old, _ := filepath.Glob(filepath.Join(dir, BinaryName()+".old-*"))
	for _, o := range old {
		os.Remove(o)
	}
	os.Remove(filepath.Join(dir, recordName))
	// Remove directories that are now empty, deepest first; anything the user put there stays.
	var dirs []string
	filepath.Walk(dir, func(p string, fi os.FileInfo, err error) error {
		if err == nil && fi.IsDir() {
			dirs = append(dirs, p)
		}
		return nil
	})
	for i := len(dirs) - 1; i >= 0; i-- {
		os.Remove(dirs[i])
	}
	return removed, moved, nil
}

// ErrNotInstalled means there is no install record in the directory.
var ErrNotInstalled = errors.New("SessionKeep is not installed there")
